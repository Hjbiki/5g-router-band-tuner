//! Crash-safe pending-change journal (§7.2).
//!
//! `<app_data>/pending-change.json` holds the in-flight safe-apply. Every write goes to a temp
//! file that is fsynced and renamed over the journal, so a crash leaves either the old or the new
//! record, never a torn one. Closed journals move to `journal-archive/` (newest 20 kept).
//!
//! The record holds network configs only: no credentials, tokens or device identifiers.
//!
//! `JournalRecord` is generic over the change target (the band config by default). Another kind
//! of change keeps its own file and archive through `Journal::with_files`, and reads and writes
//! them with the `*_record` methods.

use std::fs::{self, File};
use std::io::{self, Write};
use std::path::{Path, PathBuf};

use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::NetConfig;

pub const JOURNAL_VERSION: u32 = 1;
const JOURNAL_FILE: &str = "pending-change.json";
const ARCHIVE_DIR: &str = "journal-archive";
const ARCHIVE_KEEP: usize = 20;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum JournalPhase {
    Journaled,
    Applied,
    Verified,
    ReattachGrace,
    Probation,
    Committed,
    Reverting,
    Reverted,
    RevertFailed,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export, concrete(T = NetConfig))]
pub struct JournalRecord<T = NetConfig> {
    pub version: u32,
    /// uuid v4, generated by `SafeApply` on Start.
    pub id: String,
    pub driver: String,
    pub host: String,
    pub previous: T,
    pub requested: T,
    pub phase: JournalPhase,
    /// Wall clock, stamped by the caller. Audit only: never used for timing.
    #[ts(type = "number")]
    pub phase_changed_at_ms: u64,
    #[ts(type = "number")]
    pub created_at_ms: u64,
}

pub struct Journal {
    dir: PathBuf,
    file: String,
    archive_dir: String,
}

impl Journal {
    /// The band journal: `pending-change.json` and `journal-archive/`.
    pub fn new(dir: PathBuf) -> Self {
        Self::with_files(dir, JOURNAL_FILE, ARCHIVE_DIR)
    }

    /// A journal kept in `dir/<file>`, archived to `dir/<archive>/`.
    pub fn with_files(dir: PathBuf, file: &str, archive: &str) -> Self {
        Self {
            dir,
            file: file.to_string(),
            archive_dir: archive.to_string(),
        }
    }

    /// `Ok(None)` when there is no pending change. A corrupt file is an `InvalidData` error,
    /// never silently treated as "no journal".
    pub fn load(&self) -> Result<Option<JournalRecord>, io::Error> {
        self.load_record()
    }

    pub fn write(&self, r: &JournalRecord) -> io::Result<()> {
        self.write_record(r)
    }

    /// Moves the record to `journal-archive/<created_at_ms>-<id>.json`, removes the pending
    /// journal and prunes the archive to the newest 20.
    pub fn archive(&self, r: &JournalRecord) -> io::Result<()> {
        self.archive_record(r)
    }

    /// The archived record of change `id`, if it is still in `journal-archive/`. Used at launch
    /// to learn how a step of a two-step apply ended while the app was closed.
    pub fn archived(&self, id: &str) -> io::Result<Option<JournalRecord>> {
        self.archived_record(id)
    }

    /// `load` for any change target.
    pub fn load_record<T: DeserializeOwned>(&self) -> io::Result<Option<JournalRecord<T>>> {
        match fs::read(self.dir.join(&self.file)) {
            Ok(bytes) => serde_json::from_slice(&bytes)
                .map(Some)
                .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e)),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e),
        }
    }

    /// `write` for any change target.
    pub fn write_record<T: Serialize>(&self, r: &JournalRecord<T>) -> io::Result<()> {
        fs::create_dir_all(&self.dir)?;
        write_atomic(&self.dir, &self.file, &to_json(r)?)
    }

    /// `archive` for any change target.
    pub fn archive_record<T: Serialize>(&self, r: &JournalRecord<T>) -> io::Result<()> {
        let archive = self.dir.join(&self.archive_dir);
        fs::create_dir_all(&archive)?;
        let name = format!("{}-{}.json", r.created_at_ms, safe_id(&r.id));
        write_atomic(&archive, &name, &to_json(r)?)?;
        match retry_transient(|| fs::remove_file(self.dir.join(&self.file))) {
            Ok(()) => sync_dir(&self.dir),
            Err(e) if e.kind() == io::ErrorKind::NotFound => {}
            Err(e) => return Err(e),
        }
        prune(&archive)
    }

    /// `archived` for any change target.
    pub fn archived_record<T: DeserializeOwned>(
        &self,
        id: &str,
    ) -> io::Result<Option<JournalRecord<T>>> {
        let archive = self.dir.join(&self.archive_dir);
        let suffix = format!("-{}.json", safe_id(id));
        let entries = match fs::read_dir(&archive) {
            Ok(e) => e,
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(e),
        };
        for name in entries
            .filter_map(|e| e.ok())
            .filter_map(|e| e.file_name().into_string().ok())
            .filter(|n| n.ends_with(&suffix))
        {
            let bytes = fs::read(archive.join(&name))?;
            let rec: JournalRecord<T> = serde_json::from_slice(&bytes)
                .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e))?;
            if rec.id == id {
                return Ok(Some(rec));
            }
        }
        Ok(None)
    }
}

fn to_json<T: Serialize>(r: &JournalRecord<T>) -> io::Result<Vec<u8>> {
    serde_json::to_vec_pretty(r).map_err(io::Error::other)
}

/// The id ends up in a file name: keep it to characters that can't leave the archive dir.
fn safe_id(id: &str) -> String {
    let s: String = id
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .take(64)
        .collect();
    if s.is_empty() {
        "unknown".to_string()
    } else {
        s
    }
}

/// temp file → write → fsync → rename over the target → best-effort directory fsync.
/// `std::fs::rename` replaces an existing target on Windows too.
pub(crate) fn write_atomic(dir: &Path, name: &str, bytes: &[u8]) -> io::Result<()> {
    let tmp = dir.join(format!("{name}.tmp"));
    retry_transient(|| {
        let mut f = File::create(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()
    })?;
    retry_transient(|| fs::rename(&tmp, dir.join(name)))?;
    sync_dir(dir);
    Ok(())
}

/// On Windows, antivirus or the search indexer briefly opens freshly written files, and a
/// create/rename/remove then fails with a sharing violation. Retry those for up to ~1 s.
pub(crate) fn retry_transient<T>(mut op: impl FnMut() -> io::Result<T>) -> io::Result<T> {
    const ATTEMPTS: u32 = 20;
    let mut attempt = 1;
    loop {
        match op() {
            Err(e) if attempt < ATTEMPTS && is_transient(&e) => {
                std::thread::sleep(std::time::Duration::from_millis(50));
                attempt += 1;
            }
            other => return other,
        }
    }
}

/// ERROR_ACCESS_DENIED (5), ERROR_SHARING_VIOLATION (32), ERROR_LOCK_VIOLATION (33).
fn is_transient(e: &io::Error) -> bool {
    cfg!(windows) && matches!(e.raw_os_error(), Some(5 | 32 | 33))
}

/// Opening a directory fails on Windows without backup semantics; that's fine, it's best effort.
pub(crate) fn sync_dir(dir: &Path) {
    if let Ok(d) = File::open(dir) {
        let _ = d.sync_all();
    }
}

fn prune(archive: &Path) -> io::Result<()> {
    let mut entries: Vec<(u64, String)> = fs::read_dir(archive)?
        .filter_map(|e| e.ok())
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|name| name.ends_with(".json"))
        .map(|name| {
            let ms = name
                .split('-')
                .next()
                .and_then(|p| p.parse().ok())
                .unwrap_or(0);
            (ms, name)
        })
        .collect();
    entries.sort_unstable_by(|a, b| b.cmp(a));
    for (_, name) in entries.into_iter().skip(ARCHIVE_KEEP) {
        retry_transient(|| fs::remove_file(archive.join(&name)))?;
    }
    Ok(())
}
